const {test}=require('node:test');
const assert=require('node:assert/strict');
const {spawn}=require('node:child_process');
const crypto=require('node:crypto');
test('room password, members, host-only kick, plant pose/drop, delta and close',async()=>{
  const port=18789;
  const child=spawn(process.execPath,[require.resolve('./server.cjs')],{env:{...process.env,WEEDING_PORT:String(port)},stdio:['ignore','pipe','pipe']});
  try {
    await new Promise((resolve,reject)=>{child.stdout.once('data',resolve);child.once('error',reject);child.once('exit',code=>reject(new Error('server exited '+code)));});
    const call=async(route,data)=>{const r=await fetch('http://127.0.0.1:'+port+route,{method:'POST',body:JSON.stringify({protocol:10,...data})});return r.json();};
    const salt=Buffer.alloc(16).toString('base64');
    const hash=crypto.pbkdf2Sync('garden',Buffer.from(salt,'base64'),10000,32,'sha1').toString('base64');
    const world={coins:0,expanded:false,goldFinger:false,plants:[{id:0,state:0,bagOrder:-1,position:{x:0,y:0,z:0},rotation:{x:0,y:0,z:0,w:1}}]};
    assert.equal((await call('/create',{protocol:4,salt,hash,world:JSON.stringify(world)})).ok,false,'old clients must not enter sparse-state rooms');
    const host=await call('/create',{salt,hash,playerId:'host-profile',world:JSON.stringify(world)});
    assert.equal(host.ok,true);
    assert.equal(host.protocol,10);
    assert.equal((await call('/create',{protocol:8,salt,hash,world:JSON.stringify(world)})).ok,false,'protocol8 cannot apply sparse area changes');
    assert.equal((await call('/create',{protocol:7,salt,hash,world:JSON.stringify(world)})).ok,false,'protocol7 cannot apply bundle object changes');
    assert.equal((await call('/create',{protocol:6,salt,hash,world:JSON.stringify(world)})).ok,false,'old clients must not mix with sparse-section rooms');
    const room=host.room;
    assert.equal((await call('/join',{protocol:6,room,password:'garden'})).ok,false);
    assert.equal((await call('/join',{room,password:'wrong'})).ok,false);
    const guest=await call('/join',{room,password:'garden',playerId:'guest-profile'});
    assert.equal(guest.ok,true);
    const members=await call('/host',{room,token:host.token});
    assert.equal(members.members?.length,2,'room panel needs host and guest, including guests without pose');
    const member=members.members.find(m=>!m.host);
    assert.ok(member.id);
    assert.equal(guest.self,member.id,'guest must receive the same public actor ID used by tool ownership');
    assert.equal((await call('/kick',{room,token:guest.token,target:member.id})).ok,false);
    const plant={id:0,state:2,bagOrder:-1,position:{x:3,y:2,z:1},rotation:{x:0,y:0,z:.7071,w:.7071},scale:{x:1,y:1,z:1}};
    for(const [i,action] of ['pull','move','drop'].entries()){
      const sent=await call('/command',{room,token:guest.token,id:0,action,plant,clientSequence:i+1,commandId:'pose-'+i});
      assert.equal(sent.ok,true,action+' must carry transform and release');
    }
    const commands=(await call('/host',{room,token:host.token})).commands;
    assert.deepEqual(commands.map(c=>c.action),['pull','drop']);
    assert.deepEqual(commands[1].plant.position,{x:3,y:2,z:1});
    assert.equal(commands[1].clientSequence,3);
    const tool=await call('/command',{room,token:guest.token,id:-1,action:'tool:buy:shovel_mini',areaId:1,commandId:'tool-buy'});
    assert.equal(tool.ok,true);
    const toolCommand=(await call('/host',{room,token:host.token,ack:commands[1].sequence})).commands[0];
    assert.equal(toolCommand.actor,guest.self);assert.equal(toolCommand.areaId,1);assert.equal(toolCommand.action,'tool:buy:shovel_mini');
    const upgradeActions=['tool:buy:bag_small','tool:buy:bag_large','tool:buy:sprint','tool:equip','tool:stow'];
    for(const [index,action] of upgradeActions.entries())assert.equal((await call('/command',{room,token:guest.token,id:-1,action,commandId:'upgrade-'+index})).ok,true);
    const upgrades=(await call('/host',{room,token:host.token,ack:toolCommand.sequence})).commands;
    assert.deepEqual(upgrades.map(c=>c.action),upgradeActions);
    const bundleActions=['bundle:pack','bundle:pickup','bundle:drop','bundle:throw'];
    for(const [index,action] of bundleActions.entries())assert.equal((await call('/command',{room,token:guest.token,id:index===0?-1:1,action,areaId:1,plant,commandId:'bundle-'+index})).ok,true,action);
    assert.equal((await call('/command',{room,token:guest.token,id:1,action:'bundle:throw',areaId:1,plant,commandId:'bundle-3'})).ok,true);
    const bundleCommands=(await call('/host',{room,token:host.token,ack:upgrades[upgrades.length-1].sequence})).commands;
    assert.deepEqual(bundleCommands.map(c=>c.action),bundleActions);assert.ok(bundleCommands.every(c=>c.actor===guest.self&&c.areaId===1));
    for(const [index,action] of ['eject','collect','sell'].entries())assert.equal((await call('/command',{room,token:guest.token,id:-20001,action,areaId:1,plant,commandId:'carried-'+index})).ok,true);
    const carriedCommands=(await call('/host',{room,token:host.token,ack:bundleCommands[bundleCommands.length-1].sequence})).commands;
    assert.deepEqual(carriedCommands.map(c=>c.action),['eject','collect','sell']);assert.ok(carriedCommands.every(c=>c.id===-20001&&c.actor===guest.self));
    await call('/host',{room,token:host.token,ack:carriedCommands[carriedCommands.length-1].sequence});
    await call('/poll',{room,token:guest.token,revision:1,activeSeconds:12.5,pose:{position:{x:0,y:1.58,z:0},yaw:0}});
    const identity=(await call('/host',{room,token:host.token})).peers.find(p=>p.id===guest.self);
    assert.equal(identity.playerId,'guest-profile');assert.equal(identity.activeSeconds,12.5);
    await call('/poll',{room,token:guest.token,revision:1,activeSeconds:2,pose:{position:{x:0,y:1.58,z:0},yaw:0}});
    assert.equal((await call('/host',{room,token:host.token})).peers.find(p=>p.id===guest.self).activeSeconds,12.5,'stale clock cannot roll back');
    const progress={exitUnlocked:true,settled:true,players:[{playerId:'guest-profile',pulls:100,seconds:12.5}]};
    const bundles={nextId:2,carriedGrass:[{id:20001,originAreaId:0,plantId:0,areaId:1,kind:1,model:0,inBag:true,bagOwner:guest.self}],settledPlants:['0:99'],items:[{id:1,areaId:1,owner:guest.self,position:{x:1,y:2,z:3},velocity:{x:12,y:8,z:0},rotation:{x:0,y:0,z:0,w:1},flying:false,contents:[{areaId:1,plantId:0,kind:1,value:5}]}]};
    const patch={contentVersion:2,plantCount:9000,sparsePlants:true,progress,bundles,coins:5,expanded:false,goldFinger:false,tools:{gloveLevel:1,bagLevel:2,sprintUnlocked:true,items:[]},areas:{currentArea:0,uniquePulls:5,areas:[]},plants:[{...plant,state:1,position:{x:3,y:.1,z:1}}],removed:[]};
    patch.merchantSaleSequence=2;patch.merchantSales=[{id:1,areaId:0,amount:1},{id:2,areaId:0,amount:5}];
    await call('/host',{room,token:host.token,ack:commands[1].sequence,patch:JSON.stringify(patch)});
    const update=await call('/poll',{room,token:guest.token,revision:1});
    assert.equal(JSON.parse(update.delta).plants[0].position.y,.1);
    assert.equal(JSON.parse(update.delta).tools.gloveLevel,1);assert.equal(JSON.parse(update.delta).areas.uniquePulls,5);
    assert.equal(JSON.parse(update.delta).tools.bagLevel,2);assert.equal(JSON.parse(update.delta).tools.sprintUnlocked,true);
    assert.deepEqual(JSON.parse(update.delta).progress,progress);assert.equal(JSON.parse(update.delta).sparsePlants,true);assert.equal(JSON.parse(update.delta).plantCount,9000);
    assert.deepEqual(JSON.parse(update.delta).bundles,bundles);
    assert.equal(JSON.parse(update.delta).merchantSaleSequence,2);assert.deepEqual(JSON.parse(update.delta).merchantSales,patch.merchantSales);
    const late=await call('/join',{room,password:'garden',playerId:'late-profile'});
    const restored=JSON.parse(late.world);assert.deepEqual(restored.progress,progress);assert.equal(restored.sparsePlants,true);assert.equal(restored.plantCount,9000);
    assert.deepEqual(restored.bundles,bundles);
    assert.equal(restored.merchantSaleSequence,2);assert.deepEqual(restored.merchantSales,patch.merchantSales);
    const redeemed={...patch,coins:10,bundles:{nextId:2,items:[]},plants:[]};
    await call('/host',{room,token:host.token,patch:JSON.stringify(redeemed)});
    const redeemedUpdate=await call('/poll',{room,token:guest.token,revision:update.revision});
    assert.deepEqual(JSON.parse(redeemedUpdate.delta).bundles.items,[]);assert.equal(JSON.parse(redeemedUpdate.delta).coins,10);
    // A slow guest must receive the last value of EACH changed section, not just
    // sections present in the latest patch. Missing and empty have different meanings.
    const baseline=redeemedUpdate.revision;
    const core={contentVersion:2,plantCount:9000,sparsePlants:true,coins:11,expanded:false,goldFinger:false,plants:[],removed:[]};
    const changedTools={gloveLevel:2,bagLevel:2,items:[]};
    const changedAreas={currentArea:0,uniquePulls:6,areas:[]};
    await call('/host',{room,token:host.token,patch:JSON.stringify({...core,sections:27,tools:changedTools,areas:changedAreas,bundles:{nextId:3,items:[]}})});
    await call('/host',{room,token:host.token,patch:JSON.stringify({...core,sections:20,coins:12,progress:{exitUnlocked:false,settled:false,players:[]}})});
    const catchup=JSON.parse((await call('/poll',{room,token:guest.token,revision:baseline})).delta);
    assert.deepEqual(catchup.tools,changedTools,'catch-up lost a non-latest tools update');
    assert.deepEqual(catchup.areas,changedAreas,'catch-up lost area metadata');
    assert.deepEqual(catchup.bundles,{nextId:3,items:[]},'empty bundle inventory must clear old data');
    assert.deepEqual(catchup.progress.players,[],'empty progress list must clear old data');
    assert.equal(catchup.coins,12);
    assert.equal(catchup.sections,31,'catch-up must preserve presence bits from earlier patches');
    const onePatch=JSON.parse((await call('/poll',{room,token:guest.token,revision:baseline+1})).delta);
    assert.equal(onePatch.tools,undefined,'unchanged sections must stay absent');
    const lateCatchup=await call('/join',{room,password:'garden'});
    assert.deepEqual(JSON.parse(lateCatchup.world).tools,changedTools,'late join world diverges from deltas');
    await call('/close',{room,token:lateCatchup.token});
    const areaWorld={...world,areas:{currentArea:1,uniquePulls:500,areas:[]}};
    await call('/host',{room,token:host.token,world:JSON.stringify(areaWorld)});
    const changed=await call('/poll',{room,token:guest.token,revision:update.revision});
    assert.equal(JSON.parse(changed.world).areas.currentArea,1,'area transition must force a fresh full world');
    assert.equal((await call('/kick',{room,token:host.token,target:member.id})).ok,true);
    assert.equal((await call('/poll',{room,token:guest.token,revision:2})).ok,false);
    assert.equal((await call('/command',{room,token:guest.token,id:0,action:'pull',commandId:'after-kick'})).ok,false);
    assert.equal((await call('/close',{room,token:host.token})).ok,true);
    assert.equal((await call('/join',{room,password:'garden'})).ok,false);
    const bigWorld=JSON.stringify({plants:[],message:'草'.repeat(1500000)});
    const bigHost=await call('/create',{salt,hash,world:bigWorld});assert.equal(bigHost.ok,true,'multibyte world over old 4 MiB limit must fit new limit');
    const bigGuest=await call('/join',{room:bigHost.room,password:'garden'});assert.equal(bigGuest.ok,true);
    assert.equal(JSON.parse(bigGuest.world).message,'草'.repeat(1500000),'chunked UTF-8 world must remain intact');
    await call('/close',{room:bigHost.room,token:bigHost.token});
  } finally {child.kill();}
});
